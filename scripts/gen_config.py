"""Generate ``crates/lgbm-core/src/config/auto.rs`` from upstream ``config.h``.

Port of upstream's ``.ci/parameter-generator.py``: the same annotations in
``third_party/lightgbm/config.h`` (``alias``, ``check``, ``[no-save]``,
``[no-automatically-extract]``) drive the alias table, parameter set, typed parsing with
checks, and ``SaveMembersToString``. Defaults come from the C++ initializers.

Usage: ``python scripts/gen_config.py [--check]`` (``--check`` fails if the output is stale).
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
CONFIG_H = ROOT / "third_party" / "lightgbm" / "config.h"
OUT = ROOT / "crates" / "lgbm-core" / "src" / "config" / "auto.rs"

CONSTANTS = {"kDefaultNumLeaves": "31"}

RUST_TYPES = {
    "int": "i32",
    "double": "f64",
    "bool": "bool",
    "std::string": "String",
    "std::vector<double>": "Vec<f64>",
    "std::vector<std::string>": "Vec<String>",
    "std::vector<int8_t>": "Vec<i8>",
    "std::vector<int32_t>": "Vec<i32>",
    "std::vector<int>": "Vec<i32>",
    "TaskType": "TaskType",
}

Info = dict[str, Any]


def parse_config_h(path: Path) -> tuple[list[tuple[str, int]], list[list[Info]]]:
    """Same parsing rules as upstream's ``get_parameter_infos``, plus C++ initializers."""
    is_inparameter = False
    cur_key: str | None = None
    key_lvl = 0
    cur_info: Info = {}
    keys: list[tuple[str, int]] = []
    member_infos: list[list[Info]] = []
    for raw in path.read_text().splitlines():
        if raw.strip() in {"#ifndef __NVCC__", "#endif  // __NVCC__"}:
            continue
        if "#pragma region Parameters" in raw:
            is_inparameter = True
        elif "#pragma region" in raw and "Parameters" in raw:
            key_lvl += 1
            cur_key = raw.split("region")[1].strip()
            keys.append((cur_key, key_lvl))
            member_infos.append([])
        elif "#pragma endregion" in raw:
            key_lvl -= 1
            if cur_key is not None:
                cur_key = None
            elif is_inparameter:
                is_inparameter = False
        elif cur_key is not None:
            line = raw.strip()
            if line.startswith("//"):
                key, _, val = line[2:].partition("=")
                key, val = key.strip(), val.strip()
                if key in ("desc", "descl2"):
                    continue
                cur_info.setdefault(key, []).append(val)
            elif line:
                m = re.match(r"^([\w:<>,\s]+?)\s+(\w+)\s*(?:=\s*(.*?))?;$", line)
                if not m:
                    raise ValueError(f"cannot parse declaration: {line}")
                cur_info["inner_type"] = m.group(1).strip()
                cur_info["name"] = m.group(2)
                cur_info["init"] = m.group(3)
                member_infos[-1].append(cur_info)
                cur_info = {}
    return keys, member_infos


def parse_check(check: str) -> tuple[str, str]:
    for sign in ("<=", ">=", "<", ">"):
        if check.startswith(sign):
            value = check[len(sign) :].strip()
            float(value)
            return value, sign
    raise ValueError(f"bad check {check!r}")


def rust_default(info: Info) -> str:
    cty: str = info["inner_type"]
    init: str | None = info["init"]
    rty = RUST_TYPES[cty]
    if rty.startswith("Vec"):
        if init not in (None, ""):
            raise ValueError(f"unsupported vector initializer for {info['name']}: {init}")
        return "Vec::new()"
    if init is None:
        raise ValueError(f"missing initializer for {info['name']}")
    if rty == "TaskType":
        return {"TaskType::kTrain": "TaskType::Train"}[init]
    init = CONSTANTS.get(init, init)
    if rty == "String":
        return f"String::from({init})" if init != '""' else "String::new()"
    if rty == "f64":
        lit = init.rstrip("fF")
        if not re.search(r"[.eE]", lit):
            lit += ".0"
        return lit
    if rty == "bool":
        return init
    return init


def rust_literal(value: str, rty: str) -> str:
    if rty == "f64" and not re.search(r"[.eE]", value):
        return value + ".0"
    return value


def generate() -> str:
    _, infos = parse_config_h(CONFIG_H)
    params = [y for x in infos for y in x]
    aliases: list[tuple[str, str]] = []
    names_with_aliases: dict[str, list[str]] = defaultdict(list)
    for p in params:
        if "alias" in p:
            for a in p["alias"][0].split(","):
                aliases.append((a.strip(), p["name"]))
                names_with_aliases[p["name"]].append(a.strip())

    out: list[str] = []
    w = out.append
    w("// @generated by scripts/gen_config.py from third_party/lightgbm/config.h — do not edit.")
    w("// upstream: src/io/config_auto.cpp (generated by .ci/parameter-generator.py)")
    w("#![allow(clippy::all)]")
    w("")
    w("use std::collections::HashMap;")
    w("")
    w("use super::{TaskType, check, get_bool, get_double, get_int, get_string, get_string_field};")
    w("use crate::error::Result;")
    w("use crate::utils::format::format_g;")
    w("")
    w("/// All LightGBM parameters (upstream `Config` members), with upstream defaults.")
    w("#[derive(Debug, Clone, PartialEq)]")
    w("pub struct Config {")
    for p in params:
        w(f"    pub {p['name']}: {RUST_TYPES[p['inner_type']]},")
    w("    /// Derived from `auc_mu_weights` (upstream `GetAucMuWeights`).")
    w("    pub auc_mu_weights_matrix: Vec<Vec<f64>>,")
    w("    /// Derived from `interaction_constraints` (upstream `GetInteractionConstraints`).")
    w("    pub interaction_constraints_vector: Vec<Vec<i32>>,")
    w("    pub is_parallel: bool,")
    w("    pub is_data_based_parallel: bool,")
    w("}")
    w("")
    w("impl Default for Config {")
    w("    fn default() -> Self {")
    w("        Config {")
    for p in params:
        w(f"            {p['name']}: {rust_default(p)},")
    w("            auc_mu_weights_matrix: Vec::new(),")
    w("            interaction_constraints_vector: Vec::new(),")
    w("            is_parallel: false,")
    w("            is_data_based_parallel: false,")
    w("        }")
    w("    }")
    w("}")
    w("")
    w(
        "/// upstream: `Config::alias_table()` as `(alias, canonical name)` pairs, "
        "in declaration order."
    )
    w("pub const ALIAS_TABLE: &[(&str, &str)] = &[")
    for a, n in aliases:
        w(f'    ("{a}", "{n}"),')
    w("];")
    w("")
    w("/// upstream: `Config::parameter_set()`, in declaration order.")
    w("pub const PARAMETER_SET: &[&str] = &[")
    for p in params:
        w(f'    "{p["name"]}",')
    w("];")
    w("")
    w("/// upstream: `Config::parameter2aliases()`.")
    w("pub const PARAMETER_TO_ALIASES: &[(&str, &[&str])] = &[")
    for p in params:
        al = ", ".join(f'"{a}"' for a in names_with_aliases[p["name"]])
        w(f'    ("{p["name"]}", &[{al}]),')
    w("];")
    w("")
    overrides = {
        "categorical_feature": "vector<int>",
        "ignore_column": "vector<int>",
        "interaction_constraints": "vector<vector<int>>",
    }
    w("/// upstream: `Config::ParameterTypes()` (used by language wrappers).")
    w("pub const PARAMETER_TYPES: &[(&str, &str)] = &[")
    for p in params:
        if p["name"] == "task":
            continue
        ty = overrides.get(p["name"]) or re.sub(r"int\d+_t", "int", p["inner_type"]).replace(
            "std::", ""
        )
        w(f'    ("{p["name"]}", "{ty}"),')
    w("];")
    w("")
    w("impl Config {")
    w("    /// upstream: `Config::GetMembersFromString`")
    w("    pub(crate) fn get_members_from_string(")
    w("        &mut self,")
    w("        params: &HashMap<String, String>,")
    w("    ) -> Result<()> {")
    getter = {
        "i32": "get_int",
        "f64": "get_double",
        "bool": "get_bool",
        "String": "get_string_field",
    }
    for p in params:
        if "[no-automatically-extract]" in p:
            continue
        name, rty = p["name"], RUST_TYPES[p["inner_type"]]
        if rty.startswith("Vec"):
            inner = rty[4:-1]
            parser = {
                "String": "super::split_strings",
                "f64": "super::parse_vec_f64",
                "i32": "super::parse_vec_int::<i32>",
                "i8": "super::parse_vec_int::<i8>",
            }[inner]
            w(f'        if let Some(v) = get_string(params, "{name}") {{')
            w(f"            self.{name} = {parser}(&v)?;")
            w("        }")
        else:
            w(f'        {getter[rty]}(params, "{name}", &mut self.{name})?;')
            for c in p.get("check", []):
                value, sign = parse_check(c)
                lit = rust_literal(value, rty)
                w(f'        check(self.{name} {sign} {lit}, "{name} {sign} {value}")?;')
    w("        Ok(())")
    w("    }")
    w("")
    w("    /// upstream: `Config::SaveMembersToString` (C++ stream formatting: `%g`, bools as 0/1,")
    w("    /// vectors joined by `,` at precision 17).")
    w("    pub fn save_members_to_string(&self) -> String {")
    w("        let mut s = String::new();")
    for p in params:
        if "[no-save]" in p:
            continue
        name, rty = p["name"], RUST_TYPES[p["inner_type"]]
        if rty == "f64":
            expr = f"format_g(self.{name}, 6)"
        elif rty == "bool":
            expr = f"i32::from(self.{name})"
        elif rty == "Vec<f64>":
            expr = f"super::join_f64_17(&self.{name})"
        elif rty.startswith("Vec"):
            expr = f"super::join_display(&self.{name})"
        else:
            expr = f"&self.{name}"
        w(f'        s.push_str(&format!("[{name}: {{}}]\\n", {expr}));')
    w("        s")
    w("    }")
    w("}")
    w("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = generate()
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2024"],
        input=text,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    if args.check:
        if not OUT.exists() or OUT.read_text() != formatted:
            print(f"{OUT} is stale; run python scripts/gen_config.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(formatted)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
